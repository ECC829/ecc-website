/**
 * Verified career records, keyed by player slug.
 *
 * This file is generated by `npm run import-stats` (see
 * scripts/import-cricclubs.mjs) and can also be edited by hand. Any player
 * without an entry shows "stats not yet recorded" rather than invented
 * numbers.
 */
const recordedStats = recorded;

const roleDefaults = {
  Batsman: { battingStyle: "Right-hand batter", bowlingStyle: "—" },
  Bowler: { battingStyle: "Right-hand batter", bowlingStyle: "Right-arm" },
  Allrounder: { battingStyle: "Right-hand batter", bowlingStyle: "Right-arm" },
  "Wicket Keeper": { battingStyle: "Right-hand batter", bowlingStyle: "—" },
};

export function slugify(value) {
  return value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function initialsOf(name) {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return "?";
  if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase();
  return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
}

function buildProfile(entry, slug) {
  const recorded = recordedStats[slug];
  const defaults = roleDefaults[entry.role] ?? roleDefaults.Allrounder;

  return {
    recorded: Boolean(recorded),
    matches: recorded?.matches ?? null,
    runs: recorded?.runs ?? null,
    battingAverage: recorded?.battingAverage ?? null,
    strikeRate: recorded?.strikeRate ?? null,
    wickets: recorded?.wickets ?? null,
    bowlingEconomy: recorded?.bowlingEconomy ?? null,
    bestBatting: recorded?.bestBatting ?? null,
    bestBowling: recorded?.bestBowling ?? null,
    battingStyle: recorded?.battingStyle ?? defaults.battingStyle,
    bowlingStyle: recorded?.bowlingStyle ?? defaults.bowlingStyle,
    debutSeason: recorded?.debutSeason ?? null,
    about:
      recorded?.about ??
      `${entry.short ?? entry.name.split(" ")[0]} is part of the ECC ${entry.team} squad for the ${season.year} season, listed as ${
        /^[aeiou]/i.test(entry.role) ? "an" : "a"
      } ${entry.role.toLowerCase()}. A full player bio and match record will appear here as the club logs results through the season.`,
    seasonBatting: recorded?.seasonBatting ?? [],
    seasonBowling: recorded?.seasonBowling ?? [],
  };
}

export const players = roster.map((entry) => {
  const slug = slugify(entry.name);
  return {
    ...entry,
    slug,
    displayName: entry.short ?? entry.name,
    initials: initialsOf(entry.name),
    jerseyNo: entry.jerseyNo ?? null,
    profile: buildProfile(entry, slug),
  };
});

export const playerBySlug = Object.fromEntries(players.map((p) => [p.slug, p]));

export const roles = ["Batsman", "Bowler", "Allrounder"];

export function playersByTeam(teamName) {
  return players.filter((player) => player.team === teamName);
}

export function countByRole(list = players) {
  return list.reduce((acc, player) => {
    acc[player.role] = (acc[player.role] || 0) + 1;
    return acc;
  }, {});
}
